/** Spruch des Tages für ein Datum „YYYY-MM-DD“ (Berlin). */
export function quoteForDay(isoDay: string) {
  const day = Math.floor(Date.UTC(Number(isoDay.slice(0, 4)), Number(isoDay.slice(5, 7)) - 1, Number(isoDay.slice(8, 10))) / 86_400_000);
  // Schrittweite teilerfremd zur Anzahl → alle Sprüche kommen dran, aber nicht in Listenreihenfolge
  const n = DAILY_QUOTES.length;
  return DAILY_QUOTES[(((day * 37) % n) + n) % n];
}
